'use strict';
const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const packets=fs.readFileSync(process.argv[2],'utf8').trim().split('\n').map(JSON.parse);
 const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROME_PATH?{executablePath:process.env.PLAYWRIGHT_CHROME_PATH}:{})});
 const page=await browser.newPage({viewport:{width:1280,height:960}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://**/*',route=>{
  if(route.request().url().includes('mqtt.min.js'))return route.fulfill({contentType:'application/javascript',body:`window.mockHandlers={};window.sentCommands=[];window.mqtt={connect:()=>({connected:true,on:(name,fn)=>window.mockHandlers[name]=fn,subscribe:()=>{},publish:(topic,body)=>window.sentCommands.push({topic,body:JSON.parse(body)})})};`});
  if(route.request().url().includes('lucide'))return route.fulfill({contentType:'application/javascript',body:'window.lucide={createIcons:()=>{}};'});
  return route.abort();
 });
 await page.goto(process.env.DASHBOARD_URL||'http://127.0.0.1:8765/',{waitUntil:'networkidle'});
 await page.locator('#ir-attempts-tab').click();
 // Configuration is available before any scan, but only with fresh idle telemetry.
 assert(await page.locator('[data-barcode-config="apply"]').isDisabled());
 await page.evaluate(()=>{
  window.mockHandlers.connect();
  window.mockHandlers.message('rover/telemetry',JSON.stringify({mode:'idle',state:'online',ts_ms:0}));
  window.mockHandlers.message('rover/barcode',JSON.stringify({v:1,type:'barcode_state',boot:99,seq:1,scan:0,ts_ms:0,lag_ms:0,dropped:0,state:0,count:0,samples:0,sample_drops:0,partial:0,blocked:1,config:Array(11).fill(0)}));
 });
 assert(await page.locator('[data-barcode-config="apply"]').isEnabled());
 await page.locator('[data-barcode-config="offset"]').fill('100'); // Synthetic test measurement only.
 await page.locator('[data-barcode-config="apply"]').click();
 assert.deepEqual(await page.evaluate(()=>window.sentCommands.map(x=>x.body)),[{cmd:'barcode_config',min_element_mm:3,offset_left_mm:100},{cmd:'barcode_mode',mode:1}]);
 await page.evaluate(()=>window.mockHandlers.message('rover/barcode',JSON.stringify({v:1,type:'barcode_state',boot:99,seq:2,scan:0,ts_ms:10,lag_ms:0,dropped:0,state:6,count:0,samples:0,sample_drops:0,partial:0,blocked:1,config:[2000,2500,0,400,600,300,1000,1500,650,3870,3870],readiness:[2000,0,0,3000,53,75,106,1]})));
 assert.match(await page.locator('[data-barcode-config="status"]').textContent(),/confirmed/);
 assert.match(await page.locator('[data-barcode="status"]').textContent(),/press GP21/);
 assert.match(await page.locator('[data-barcode="readiness"]').textContent(),/raw 2000/);
 await page.evaluate(()=>window.mockHandlers.message('rover/barcode',JSON.stringify({v:1,type:'barcode_state',boot:99,seq:3,scan:0,ts_ms:20,lag_ms:0,dropped:0,state:6,count:0,samples:0,sample_drops:0,partial:0,blocked:32,readiness:[2000,0,0,0,106,75,106,2]})));
 assert.match(await page.locator('[data-barcode="status"]').textContent(),/sampling too coarse/);
 assert.match(await page.locator('[data-barcode="readiness"]').textContent(),/1.06 mm/);
 await page.evaluate(()=>window.mockHandlers.message('rover/telemetry',JSON.stringify({mode:'line',state:'online',ts_ms:20})));
 assert(await page.locator('[data-barcode-config="apply"]').isDisabled());
 await page.reload({waitUntil:'networkidle'});
 await page.locator('#ir-attempts-tab').click();
 const send=async messages=>page.evaluate(messages=>{for(const p of messages)window.mockHandlers.message('rover/barcode',JSON.stringify(p));},messages);
 const cut=packets.findIndex(p=>p.type==='barcode_edges'&&p.rows.some(r=>r[0]>=4))+1;
 await send(packets.slice(0,cut));
 await page.waitForFunction(()=>document.querySelectorAll('[data-barcode="elements"] button').length>0);
 assert(!/decoded/.test(await page.locator('[data-barcode="outcome"]').textContent()));
 await page.locator('[data-barcode="pause"]').click();
 const frozen=await page.locator('[data-barcode="strip"] rect').count();
 await send(packets.slice(cut));
 assert.equal(await page.locator('[data-barcode="strip"] rect').count(),frozen);
 await page.locator('[data-barcode="pause"]').click();
 await page.locator('[data-barcode="scan"]').selectOption('123:1');
 assert.match(await page.locator('[data-barcode="outcome"]').textContent(),/decoded F \(forward\)/);
 assert.equal(await page.locator('[data-barcode="strip"] rect').count(),29);
 assert.equal(await page.locator('[data-barcode="reference"] rect').count(),29);
 await page.locator('[data-barcode="elements"] button').first().click();
 assert.match(await page.locator('[data-barcode="detail"]').textContent(),/Element 1/);
 await page.locator('[data-barcode="sample"]').fill('12');
 assert.match(await page.locator('[data-barcode="sample-detail"]').textContent(),/Sample 13/);
 await page.locator('[data-barcode="expected"]').selectOption('Y');
 assert(await page.locator('[data-mismatch="true"]').count()>0);
 assert.match(await page.locator('[data-barcode="outcome"]').textContent(),/decoded F/);
 await page.locator('[data-barcode="expected"]').selectOption('F');
 await page.locator('#barcode-visual').screenshot({path:'/private/tmp/barcode-desktop.png'});
 await page.locator('[data-barcode="scan"]').selectOption('123:2');
 assert.match(await page.locator('[data-barcode="outcome"]').textContent(),/decoded F \(reverse\)/);
 await page.locator('[data-barcode="scan"]').selectOption('123:3');
 assert.match(await page.locator('[data-barcode="outcome"]').textContent(),/Rejected/);
 assert(await page.locator('[data-barcode="strip"] rect').count()>0);
 const downloadPromise=page.waitForEvent('download');await page.locator('[data-barcode="export"]').click();
 const download=await downloadPromise;await download.saveAs('/private/tmp/barcode-replay.json');
 await page.locator('[data-barcode="clear"]').click();
 await page.locator('[data-barcode="import"]').setInputFiles('/private/tmp/barcode-replay.json');
 await page.waitForFunction(()=>document.querySelector('[data-barcode="notice"]').textContent.includes('Imported scan'));
 assert.equal(await page.locator('[data-barcode="scan"] option').count(),3);
 await page.locator('[data-barcode="pause"]').click();
 const first=packets.find(p=>p.type==='barcode_start'),end=packets.find(p=>p.type==='barcode_end'),last=packets[packets.length-1].seq;
 await send([{...first,scan:4,seq:last+3},{...end,scan:4,seq:last+4}]);
 await page.locator('[data-barcode="scan"]').selectOption('123:4');
 assert.match(await page.locator('[data-barcode="outcome"]').textContent(),/evidence incomplete/);
 assert.equal(await page.locator('.barcode-unknown').count(),1);
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.locator('[data-barcode="import"]').setInputFiles('/private/tmp/barcode-replay.json');
 await page.waitForFunction(()=>document.querySelectorAll('[data-barcode="scan"] option').length===3);
 await page.locator('[data-barcode="scan"]').selectOption('123:1');
 await page.locator('#barcode-visual').screenshot({path:'/private/tmp/barcode-mobile.png'});
 await page.evaluate(()=>window.mockHandlers.close());
 assert.match(await page.locator('[data-barcode="status"]').textContent(),/unavailable/);
 assert.deepEqual(errors,[]);
 console.log('PASS: firmware MQTT -> browser growing strip, no premature letter, frozen scans, F both orientations, independent reference, raw samples, rejected evidence, export/import, gap and mobile layout');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
