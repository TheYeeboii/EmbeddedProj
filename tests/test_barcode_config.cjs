'use strict';
const assert=require('node:assert/strict');
const Configuration=require('../dashboard/barcode-config.js');
const nodes={};
for(const name of ['minimum','offset','apply','status','active'])nodes[name]={value:name==='minimum'?'3':'',textContent:'',disabled:false,focus(){this.focused=true;}};
const form={querySelector(selector){return nodes[selector.match(/"(.*?)"/)[1]];},addEventListener(){}};
const sent=[];let now=0,allow=true;
const ui=new Configuration(form,{clock:()=>now,schedule:()=>null,send:(cmd,values)=>{if(!allow)return false;sent.push({cmd,...values});return true;}});
const state=(seq,enabled,extra={})=>({type:'barcode_state',boot:7,seq,state:enabled?6:0,lag_ms:0,config:enabled?[2000,2500,0,400,600,300,1000,1500,650,3870,3870]:Array(11).fill(0),...extra});
assert(nodes.apply.disabled);assert(!ui.submit());
ui.robot('idle');assert(!nodes.apply.disabled);
assert(!ui.submit());assert(nodes.offset.focused);assert.equal(sent.length,0);
nodes.offset.value='100';nodes.minimum.value='0';assert(!ui.submit());
nodes.minimum.value='3.5';assert(!ui.submit());
nodes.minimum.value='3';nodes.offset.value='501';assert(!ui.submit());
nodes.offset.value='100';ui.reader(state(1,false));assert.match(nodes.active.textContent,/disabled/);
assert(ui.submit());assert(nodes.apply.disabled);
assert.deepEqual(sent,[{cmd:'barcode_config',min_element_mm:3,offset_left_mm:100},{cmd:'barcode_mode',mode:1}]);
ui.reader(state(2,true,{lag_ms:1000}));assert(ui.pending); // Buffered state cannot confirm live settings.
ui.reader(state(3,true));assert(!ui.pending);assert.match(nodes.status.textContent,/confirmed/);
assert.match(nodes.active.textContent,/100 mm/);
ui.robot('line');assert(nodes.apply.disabled);assert(!ui.submit());assert.equal(sent.length,2);
ui.robot('idle');nodes.offset.value='-90';assert(ui.submit());
assert.equal(sent[2].offset_left_mm,-90);now=5001;ui.refresh();assert(!ui.pending);assert.match(nodes.status.textContent,/stale/);
ui.robot('idle');allow=false;assert(!ui.submit());assert.match(nodes.status.textContent,/not sent/);
allow=true;assert(ui.submit());ui.reader(state(4,true,{config:undefined}));
assert(!ui.pending);assert.match(nodes.status.textContent,/does not report|rebuild current firmware/);
ui.reader(state(1,false,{boot:8}));assert.match(nodes.status.textContent,/restarted/);assert.match(nodes.active.textContent,/disabled/);
ui.unavailable();assert(nodes.apply.disabled);assert(!ui.submit());
assert(sent.every(x=>['barcode_config','barcode_mode'].includes(x.cmd)));
console.log('PASS: stopped-only barcode setup, measurement validation, observe-only commands, active settings, stale/timeout/reboot handling and older firmware fallback');
