'use strict';
const assert=require('node:assert/strict');
const {IRStreamHistory,valid,viewport}=require('../dashboard/ir-stream-model.js');
const row=(seq,time,black=0,flags=17)=>[seq,time,black?2500:2000,black?1000:0,black,0,0,flags,2000,2500,0];
const packet=(rows,extra={})=>({v:1,type:'ir_stream',boot:7,ts_ms:rows.at(-1)[1],lag_ms:0,dropped:0,period_ms:10,white:140,black:210,rows,...extra});
const h=new IRStreamHistory();
assert(h.accept(packet([row(1,10),row(2,20,1),row(3,30,1),row(4,40)]),40));
assert.equal(h.live.row[4],0);
const view=viewport(h.records,null,5000);
assert(view.segments.some(s=>s.value===1&&s.to-s.from===20)); // Black pulse survives although latest state is white.
assert(h.records.every(r=>r.row[5]===0&&r.row[6]===0));
assert(h.accept(packet([row(7,70,1,32)]),70));
assert.equal(h.records.at(-1).gap,'missing_samples');
assert(viewport(h.records,null,5000).segments.some(s=>s.value===null));
assert(h.accept(packet([row(8,150,0)])));assert.equal(h.records.at(-1).gap,'sampling_gap');
assert(!h.accept(packet([row(7,70,1)])));assert(!h.accept(packet([row(8,150,0)])));
const frozen=h.records.slice();h.accept(packet([row(9,160,1)]));assert.equal(frozen.length,6);assert.equal(h.records.length,7);
assert.deepEqual(IRStreamHistory.read(h.export()),h.records);
h.unavailable();assert.equal(h.live,null);
assert(h.accept(packet([row(10,170,0)],{lag_ms:1000})));assert.equal(h.live,null);
assert(h.accept(packet([row(1,10,1)],{boot:8})));assert.equal(h.records.at(-1).gap,'boot');
assert(!h.accept(packet([row(11,180)],{boot:7})));
assert(!valid(packet([row(1,0),row(3,10)])));
assert(!valid(packet([[1,0,5000,0,0,0,0,0,0,4095,0]])));
assert.throws(()=>IRStreamHistory.read('x'.repeat(4000001)));
assert.throws(()=>IRStreamHistory.read(JSON.stringify({format:'rover-ir-stream-v1',evicted:0,records:[{boot:1,row:row(1,0),gap:null,dropped:0},{boot:1,row:row(3,30),gap:null,dropped:0}]})));
const bounded=new IRStreamHistory(3);
bounded.accept(packet([row(1,10),row(2,20),row(3,30),row(4,40)]));assert.equal(bounded.records.length,3);assert.equal(bounded.evicted,1);
const wrap=new IRStreamHistory();assert(wrap.accept(packet([row(0xffffffff,0xfffffff0,1)])));assert(wrap.accept(packet([row(0,5,0)])));
console.log('PASS: continuous black pulse without frames or motion, missing/sampling gaps, pause snapshot, replay, delayed/reordered/reboot/wrap data and bounded history');
